const getDateDaysAgo = (days) => {
  const d = new Date()
  d.setDate(d.getDate() - days)
  return d.toISOString().split('T')[0]
}

const getDateTimeDaysAgo = (days, time = '11:30 AM') => {
  const dateStr = getDateDaysAgo(days)
  return `${dateStr}T12:00:00.000Z`
}

